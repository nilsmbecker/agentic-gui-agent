#!/usr/bin/env python3
"""STEP 1 — Let the model call a tool, execute it, and return the result."""

import argparse
import json

import common as C
from lab_support import Lab, pretty


TOOLS = [{
    "type": "function",
    "function": {
        "name": "multiply",
        "description": "Multiply two integers exactly.",
        "parameters": {
            "type": "object",
            "properties": {
                "a": {"type": "integer"},
                "b": {"type": "integer"},
            },
            "required": ["a", "b"],
            "additionalProperties": False,
        },
    },
}]

SYSTEM = "Use the supplied multiply tool for multiplication, then report its result briefly."
USER_TEXT = "Use multiply to calculate 30 times 23."


def execute_tool(call):
    """Validate the model's arguments; only Python executes the tool."""
    if not isinstance(call, dict) or not isinstance(call.get("function"), dict):
        return {"error": "A tool call must contain a function object."}
    function = call["function"]
    if function.get("name") != "multiply":
        return {"error": "Unknown tool. Only multiply is available."}

    arguments = function.get("arguments", {})
    if isinstance(arguments, str):
        try:
            arguments = json.loads(arguments)
        except json.JSONDecodeError:
            return {"error": "Arguments must be a JSON object."}

    if not isinstance(arguments, dict) or set(arguments) != {"a", "b"}:
        return {"error": "Supply exactly a and b."}
    if any(type(value) is not int or abs(value) > 10000
           for value in arguments.values()):
        return {"error": "a and b must be integers between -10000 and 10000."}
    return {"result": arguments["a"] * arguments["b"]}


def select_tool_model(model=None):
    """Use the shared 4B default or an explicit override, and require tools."""
    selected = model or C.resolve_model()
    if "tools" in C.capabilities(selected):
        return selected
    C.die(
        f"{selected} does not advertise Ollama tools support.\n"
        "Inspect capabilities with: ollama show <tag>\n"
        "Select a tools-capable 4B model with --model <tag> or OLLAMA_MODEL."
    )


def run_conversation(lab, messages, max_rounds=4):
    """Keep the actual model messages and execute every returned tool call."""
    tool_calls = 0
    successful_tools = 0
    model_calls = 0
    stop_reason = "max_rounds"
    error = None

    try:
        for round_number in range(1, max_rounds + 1):
            # Every request includes the complete conversation so far.
            request = lab.request(messages, tools=TOOLS)
            stop_reason = "model_error"
            if not lab.dry_run:
                model_calls += 1
            response = lab.call(request, f"model request {round_number}", show=True)

            if lab.dry_run:
                stop_reason = "dry_run"
                print("\n[dry run] First request only; no model reply or tool execution.")
                break

            stop_reason = "invalid_response"
            if not isinstance(response, dict):
                raise ValueError("Expected a JSON response object.")
            message = response.get("message")
            if not isinstance(message, dict) or message.get("role") != "assistant":
                raise ValueError("Expected an assistant message from the model.")

            # This assistant message comes directly from Ollama, not from us.
            messages.append(message)
            if response.get("done_reason") == "length":
                stop_reason = "output_limit"
                error = "Model output hit num_predict; no truncated tool call will be executed."
                break

            calls = message.get("tool_calls", [])
            if not isinstance(calls, list):
                raise ValueError("assistant.tool_calls must be a list.")

            if not calls:
                answer = message.get("content", "")
                if not isinstance(answer, str) or not answer.strip():
                    raise ValueError("The model returned neither tool calls nor an answer.")
                print("\n[assistant answer]\n" + answer)
                if tool_calls == 0:
                    stop_reason = "no_tool_call"
                    error = "The model answered without calling a tool; tool use was not demonstrated."
                elif successful_tools == 0:
                    stop_reason = "tool_error"
                    error = "The model stopped, but no tool execution succeeded."
                else:
                    stop_reason = "final_answer"
                break

            print("\n[tool calls generated by the model]")
            print(pretty(calls))
            for call in calls:
                if not isinstance(call, dict) or not isinstance(call.get("function"), dict):
                    raise ValueError("Each tool call must contain a function object.")
                name = call["function"].get("name")
                if not isinstance(name, str) or not name:
                    raise ValueError("Each tool call must name a function.")

                result = execute_tool(call)
                tool_calls += 1
                successful_tools += int("result" in result)
                print(f"\n[Python executes {name}]\n{pretty(result)}")
                # Errors are returned too, so the model can correct its arguments.
                messages.append({
                    "role": "tool",
                    "tool_name": name,
                    "content": json.dumps(result),
                })
        else:
            stop_reason = "max_rounds"
            error = f"Stopped after {max_rounds} model requests without a final answer."
    except KeyboardInterrupt:
        stop_reason = "interrupted"
        error = "Interrupted before the conversation completed."
    except (Exception, SystemExit) as exc:
        error = (f"Model request failed (exit {exc.code}); see the Ollama error above."
                 if isinstance(exc, SystemExit) else str(exc))
    finally:
        lab.save(
            stop_reason=stop_reason,
            stopped_on_error=error is not None,
            error=error,
            model_calls=model_calls,
            tool_calls=tool_calls,
            successful_tools=successful_tools,
            final_messages=messages,
        )

    if error is not None:
        print(f"\nStopped: {error}")
        return 130 if stop_reason == "interrupted" else 1
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--model", help="Explicit Ollama model tag; must support tools.")
    parser.add_argument("--max-rounds", type=int, default=4,
                        help="Maximum model requests, including the final answer (default: 4).")
    args = parser.parse_args(argv)
    if not 2 <= args.max_rounds <= 10:
        parser.error("--max-rounds must be between 2 and 10.")

    model = args.model if args.dry_run else select_tool_model(args.model)
    lab = Lab(1, "Model-generated tool calls and results", args.dry_run, model=model)
    messages = [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": USER_TEXT},
    ]
    exit_code = run_conversation(lab, messages, args.max_rounds)
    if exit_code == 0:
        print(C.rule("what you should have noticed"))
        print("""  * Tool definitions are a top-level request field.
  * The model generates assistant.tool_calls, including the arguments.
  * Python validates and executes the tool, then appends a role=tool result.
  * The next model request includes that assistant message AND the tool result.
  * The model produces the final answer; dry run only previews request 1.

  Check: trace both requests and responses in artifacts/step1.json.
  Next: python3 step2_prefix_cache.py""")
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
